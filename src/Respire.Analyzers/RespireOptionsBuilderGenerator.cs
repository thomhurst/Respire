using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Respire.Analyzers;

/// <summary>Generates the DI builder from the core options contract, including future properties.</summary>
[Generator]
public sealed class RespireOptionsBuilderGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var source = context.CompilationProvider.Select(static (compilation, _) => Generate(compilation));
        context.RegisterSourceOutput(source, static (output, text) =>
        {
            if (text is not null)
                output.AddSource("RespireOptionsBuilder.g.cs", SourceText.From(text, Encoding.UTF8));
        });
    }

    private static string? Generate(Compilation compilation)
    {
        if (compilation.AssemblyName != "Respire.DependencyInjection") return null;
        var options = compilation.GetTypeByMetadataName("Respire.RespireOptions");
        if (options is null) return null;

        var format = SymbolDisplayFormat.FullyQualifiedFormat.WithMiscellaneousOptions(
            SymbolDisplayMiscellaneousOptions.EscapeKeywordIdentifiers |
            SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);
        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace Respire.DependencyInjection;\npublic sealed partial class RespireOptionsBuilder\n{\n");
        foreach (var property in options.GetMembers().OfType<IPropertySymbol>())
        {
            if (property.IsStatic || property.DeclaredAccessibility != Accessibility.Public
                || property.SetMethod?.DeclaredAccessibility != Accessibility.Public) continue;
            source.Append("    /// <inheritdoc cref=\"global::Respire.RespireOptions.").Append(property.Name).Append("\"/>\n")
                .Append("    public ").Append(property.Type.ToDisplayString(format)).Append(' ').Append(property.Name).Append("\n    {\n")
                .Append("        get => _options.").Append(property.Name).Append(";\n")
                .Append("        set => _options = _options with { ").Append(property.Name).Append(" = value };\n    }\n");
        }
        return source.Append("}\n").ToString();
    }
}
